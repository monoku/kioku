import { test } from "node:test";
import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import { mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { run } from "../../src/cli/run.ts";
import { VERB_NAMES } from "../../src/cli/verbs.ts";
import { ctx } from "../fixtures.ts";

async function completion(
  shell: string,
  o: { tty?: boolean; json?: boolean } = {},
): Promise<{ code: number; raw: string }> {
  let raw = "";
  const code = await run(
    ["completion", shell, ...(o.json ? ["--json"] : [])],
    { stdout: (t) => (raw += t), isTty: o.tty ?? false },
    ctx({ home: tmpdir() }),
  );
  return { code, raw };
}

const has = (shell: string): boolean => spawnSync(shell, ["--version"], { encoding: "utf8" }).status === 0;

test("kioku completion prints a script for fish, zsh and bash that names every verb and flag, as text even through a pipe (§6.1)", async () => {
  for (const shell of ["fish", "zsh", "bash"]) {
    const { code, raw } = await completion(shell);
    assert.equal(code, 0, shell);
    assert.match(
      raw,
      new RegExp(`^(#compdef kioku\\n)?# Completion of kioku for ${shell}, generated by kioku `),
      shell,
    );
    for (const verb of VERB_NAMES) {
      const last = verb.split(" ").at(-1)!;
      assert.ok(raw.includes(last), `${shell} completes ${verb}`);
    }
    for (const flag of ["brain", "kind", "sub", "see-also", "stale-after", "dry-run", "include-retired"])
      assert.ok(raw.includes(shell === "fish" ? `-l ${flag}` : `--${flag}`), `${shell} knows --${flag}`);
    assert.ok(raw.includes("kioku brain list --json"), `${shell} reads the brains from the machine`);
    assert.ok(raw.includes("kioku config --json"), `${shell} reads the configuration keys from the machine`);
    assert.doesNotMatch(raw, /^\{"shell"/, "a pipe gets the script, not JSON");
  }
  const json = await completion("fish", { json: true });
  assert.deepEqual(Object.keys(JSON.parse(json.raw)), ["shell", "script"]);
  const bad = await completion("ksh", { json: true });
  assert.deepEqual(JSON.parse(bad.raw).error.code, "usage");
});

test("the fish and bash scripts complete verbs, group verbs, flags and a flag's words, when those shells are here", async (t) => {
  const dir = mkdtempSync(join(tmpdir(), "kioku-completion-"));
  t.after(() => rmSync(dir, { recursive: true, force: true }));
  for (const shell of ["fish", "zsh", "bash"]) writeFileSync(join(dir, `c.${shell}`), (await completion(shell)).raw);
  if (has("zsh")) {
    assert.equal(spawnSync("zsh", ["-n", join(dir, "c.zsh")], { encoding: "utf8" }).status, 0, "zsh parses the script");
    // A profile that never started the completion system, the newcomer's: the script starts it and registers itself, quietly.
    const bare = spawnSync(
      "zsh",
      ["-f", "-c", `eval "$(cat ${join(dir, "c.zsh")})"; print -r -- ${"${+functions[_kioku]}"} ${"${_comps[kioku]}"}`],
      { encoding: "utf8", env: { ...process.env, ZDOTDIR: dir } },
    );
    assert.equal(bare.stderr, "", "nothing complained");
    assert.equal(bare.stdout, "1 _kioku\n", "the function is there and completes kioku");
  }
  if (has("fish")) {
    assert.equal(
      spawnSync("fish", ["-n", join(dir, "c.fish")], { encoding: "utf8" }).status,
      0,
      "fish parses the script",
    );
    const script = join(dir, "live.fish");
    writeFileSync(
      script,
      `source ${join(dir, "c.fish")}\nfor line in 'kioku pa' 'kioku page sa' 'kioku page save --su' 'kioku page evolve --to ' 'kioku brain create x --tier ' 'kioku config '\n    echo "> $line"\n    complete -C "$line"\nend\n`,
    );
    const out = spawnSync("fish", [script], { encoding: "utf8" }).stdout;
    assert.match(out, /> kioku pa\npage\t/);
    assert.match(out, /> kioku page sa\nsave\t/);
    assert.match(out, /> kioku page save --su\n--sub\t/);
    assert.match(
      out,
      /> kioku page evolve --to \nplaybook\tto\nrule\tto\nskill\tto\n/,
      "a flag's few words, and no files",
    );
    assert.match(out, /> kioku brain create x --tier \npersonal\ttier\nproject\ttier\nteam\ttier\n/);
    assert.match(out, /> kioku config \nget\nset\nunset\n/);
  }
  if (has("bash")) {
    assert.equal(
      spawnSync("bash", ["-n", join(dir, "c.bash")], { encoding: "utf8" }).status,
      0,
      "bash parses the script",
    );
    // The profile line `setup` writes evaluates the script: that registers it in every bash, 3.2 included, where `source <(…)` reads nothing.
    const line = spawnSync("bash", ["-c", `eval "$(cat ${join(dir, "c.bash")})"; complete -p kioku`], {
      encoding: "utf8",
    });
    assert.equal(line.stdout.trim(), "complete -F _kioku kioku", line.stderr);
    const script = join(dir, "live.bash");
    writeFileSync(
      script,
      `source ${join(dir, "c.bash")}\ntry() { COMP_WORDS=("$@"); COMP_CWORD=$(( \${#COMP_WORDS[@]} - 1 )); COMPREPLY=(); _kioku; echo "> $* => \${COMPREPLY[*]}"; }\ntry kioku pa\ntry kioku page sa\ntry kioku page evolve --to ''\ntry kioku brain create x --tier ''\ntry kioku config ''\n`,
    );
    const out = spawnSync("bash", [script], { encoding: "utf8" }).stdout;
    assert.match(out, /> kioku pa => page\n/);
    assert.match(out, /> kioku page sa => save\n/);
    assert.match(out, /> kioku page evolve --to  => skill rule playbook\n/);
    assert.match(out, /> kioku brain create x --tier  => personal project team\n/);
    assert.match(out, /> kioku config  => get set unset\n/);
  }
});
