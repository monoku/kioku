import { userError } from "../core/errors.ts";
import { SHELLS, type Shell } from "../core/setup/path.ts";
import { HARNESS_IDS } from "../harness/index.ts";
import { VERSION } from "../version.ts";
import {
  type Flag,
  GROUPS as ALL_GROUPS,
  GROUP_DOES,
  groupVerbs,
  HELP_DOES,
  type Takes,
  VERB_NAMES,
  VERBS,
  type VerbName,
} from "./verbs.ts";
import type { Handler, Outcome } from "./run.ts";

/**
 * `kioku completion fish|zsh|bash` (§6.1): the shell's completion script, generated from the table the verbs are
 * declared in, so the verbs, their flags and the words a flag takes are this version's. Brains and configuration keys
 * are read from the machine when the completion runs.
 */

/** A flag with its name, as a shell offers it. */
interface Named extends Flag {
  readonly name: string;
}

const TIERS = ["personal", "project", "team"];

/** The flags a person may type for a verb, as the table declares them: a hidden one is not offered. */
const flagsOf = (verb: VerbName): Named[] =>
  Object.entries(VERBS[verb].flags)
    .filter(([, f]) => f.hidden !== true)
    .map(([name, f]) => ({ name, ...f }));
const does = (verb: VerbName): string => VERBS[verb].does;
/** What the first word after the verb takes, when a shell can offer it: a brain of the machine, or one of a few words. */
const positionalOf = (verb: VerbName): "brain" | { readonly choices: readonly string[] } | undefined => {
  const p = VERBS[verb].positional;
  return p === "brain" || typeof p === "object" ? p : undefined;
};

// `plugin <host> install|uninstall` has the host between the group and the verb: completed by hand, below.
const PLUGIN_VERB_NAMES = VERB_NAMES.filter((n) => n.startsWith("plugin "));
const all: VerbName[] = VERB_NAMES.filter((n) => !PLUGIN_VERB_NAMES.includes(n));
const GROUPS = ALL_GROUPS.filter((g) => g !== "plugin");
/** The hosts' ids and `claude`, the alias `harnessIdOf` takes for Claude Code. */
const PLUGIN_HOSTS: readonly string[] = [...HARNESS_IDS, "claude"];
const PLUGIN_VERBS = groupVerbs("plugin").map((s) => s.slice(s.indexOf(" ") + 1));
/** The flags the plugin verbs share, each named once. */
const PLUGIN_FLAGS: Named[] = PLUGIN_VERB_NAMES.flatMap(flagsOf).filter(
  (f, i, list) => list.findIndex((g) => g.name === f.name) === i,
);
const tops: VerbName[] = all.filter((n) => !n.includes(" "));
const inGroup = (g: string): VerbName[] => all.filter((n) => n.startsWith(`${g} `));
const short = (verb: string): string => verb.slice(verb.indexOf(" ") + 1);
const CONFIG_WORDS = (VERBS.config.positional as { choices: readonly string[] }).choices;

/** The brains' names and the configuration's keys, read when the completion runs: one shell line each. A brain is named once, though `brain list` names it in `brains` and in `chain`. */
const BRAINS_SH = `kioku brain list --json 2>/dev/null | grep -o '"name":"[^"]*"' | cut -d'"' -f4 | sort -u`;
const KEYS_SH = `kioku config --json 2>/dev/null | grep -o '"key":"[^"]*"' | cut -d'"' -f4`;

const sq = (s: string): string => `'${s.replace(/'/g, "'\\''")}'`;

/** What a shell shows beside a flag: the usage's placeholder when it says something (`<when>`), else the flag's name (`<a,b>` says nothing). */
const label = (f: Named): string => {
  const bare = f.hint.replace(/^<|>$/g, "");
  return bare.length > 2 && !bare.includes("|") && !bare.includes(",") ? bare : f.name.replace(/-/g, " ");
};

function fish(): string {
  const out: string[] = [
    `# Completion of kioku for fish, generated by kioku ${VERSION} (kioku completion fish).`,
    "function __kioku_brains",
    `    kioku brain list --json 2>/dev/null | string match -arg '\"name\":\"([^\"]+)\"' | sort -u`,
    "end",
    "function __kioku_keys",
    `    kioku config --json 2>/dev/null | string match -arg '\"key\":\"([^\"]+)\"'`,
    "end",
    "complete -c kioku -f",
    `complete -c kioku -l json -d 'answer in JSON'`,
  ];
  const atTop = `not __fish_seen_subcommand_from ${[...tops, ...GROUPS, "plugin"].join(" ")}`;
  for (const verb of tops) out.push(`complete -c kioku -n ${sq(atTop)} -a ${verb} -d ${sq(does(verb))}`);
  for (const g of GROUPS) {
    out.push(`complete -c kioku -n ${sq(atTop)} -a ${g} -d ${sq(GROUP_DOES[g])}`);
    const subs = inGroup(g).map(short);
    const inG = `__fish_seen_subcommand_from ${g}; and not __fish_seen_subcommand_from ${subs.join(" ")}`;
    for (const verb of inGroup(g)) out.push(`complete -c kioku -n ${sq(inG)} -a ${short(verb)} -d ${sq(does(verb))}`);
  }
  out.push(`complete -c kioku -n ${sq(atTop)} -a plugin -d ${sq(GROUP_DOES.plugin)}`);
  // `help` is not among the words that end the first level: after it the same words, and a group's verbs, are offered.
  out.push(`complete -c kioku -n ${sq(atTop)} -a help -d ${sq(HELP_DOES)}`);
  out.push(
    `complete -c kioku -n ${sq(`__fish_seen_subcommand_from plugin; and not __fish_seen_subcommand_from ${PLUGIN_HOSTS.join(" ")}`)} -a ${sq(PLUGIN_HOSTS.join(" "))}`,
  );
  out.push(
    `complete -c kioku -n ${sq(`__fish_seen_subcommand_from plugin; and __fish_seen_subcommand_from ${PLUGIN_HOSTS.join(" ")}; and not __fish_seen_subcommand_from ${PLUGIN_VERBS.join(" ")}`)} -a ${sq(PLUGIN_VERBS.join(" "))}`,
  );
  for (const f of PLUGIN_FLAGS)
    out.push(
      `complete -c kioku -n ${sq(`__fish_seen_subcommand_from plugin; and __fish_seen_subcommand_from ${PLUGIN_VERBS.join(" ")}`)} -l ${f.name} -d ${sq(label(f))}`,
    );
  // `-x` wants a value and offers no files; only a path flag gets files (`-r -F`).
  const fishTakes = (t: Takes): string =>
    t === "none"
      ? ""
      : t === "brain"
        ? " -x -a '(__kioku_brains)'"
        : t === "target"
          ? ` -x -a '(__kioku_brains) ${TIERS.join(" ")}'`
          : t === "key"
            ? " -x -a '(__kioku_keys)'"
            : t === "file"
              ? " -r -F"
              : typeof t === "object"
                ? ` -x -a ${sq(t.choices.join(" "))}`
                : " -x";
  for (const verb of all) {
    const cond = verb.includes(" ")
      ? `__fish_seen_subcommand_from ${verb.split(" ")[0]}; and __fish_seen_subcommand_from ${short(verb)}`
      : `__fish_seen_subcommand_from ${verb}; and not __fish_seen_subcommand_from ${[...GROUPS, "plugin"].join(" ")}`;
    const positional = positionalOf(verb);
    if (verb === "config") {
      out.push(
        `complete -c kioku -n ${sq(`${cond}; and not __fish_seen_subcommand_from ${CONFIG_WORDS.join(" ")}`)} -a ${sq(CONFIG_WORDS.join(" "))}`,
      );
      // The key is the word right after get, set or unset (the third before the cursor); a value is not a key.
      out.push(
        `complete -c kioku -n ${sq(`${cond}; and __fish_seen_subcommand_from ${CONFIG_WORDS.join(" ")}; and test (count (commandline -opc)) -eq 3`)} -a '(__kioku_keys)'`,
      );
    } else if (positional === "brain") {
      out.push(`complete -c kioku -n ${sq(cond)} -a '(__kioku_brains)'`);
    } else if (positional !== undefined) {
      out.push(`complete -c kioku -n ${sq(cond)} -a ${sq(positional.choices.join(" "))}`);
    }
    for (const f of flagsOf(verb))
      out.push(`complete -c kioku -n ${sq(cond)} -l ${f.name}${fishTakes(f.takes)} -d ${sq(label(f))}`);
  }
  return `${out.join("\n")}\n`;
}

function zsh(): string {
  const describe = (list: VerbName[], label: (verb: VerbName) => string): string =>
    list.map((verb) => sq(`${label(verb)}:${does(verb).replace(/:/g, " ")}`)).join(" ");
  const zTakes = (f: Named): string => {
    const t = f.takes;
    const msg = label(f);
    if (t === "none") return sq(`--${f.name}[${msg}]`);
    if (t === "brain") return sq(`--${f.name}[${msg}]:brain:_kioku_brains`);
    if (t === "target") return sq(`--${f.name}[${msg}]:brain or tier:_kioku_targets`);
    if (t === "key") return sq(`--${f.name}[${msg}]:key:_kioku_keys`);
    if (t === "file") return sq(`--${f.name}[${msg}]:file:_files`);
    if (typeof t === "object") return sq(`--${f.name}[${msg}]:${f.name}:(${t.choices.join(" ")})`);
    return sq(`--${f.name}[${msg}]:${msg}:`);
  };
  const positional = (verb: VerbName, index: number): string[] => {
    if (verb === "config")
      return [sq(`${index}:action:(${CONFIG_WORDS.join(" ")})`), sq(`${index + 1}:key:_kioku_keys`)];
    const p = positionalOf(verb);
    if (p === "brain") return [sq(`${index}:brain:_kioku_brains`)];
    if (p !== undefined) return [sq(`${index}:word:(${p.choices.join(" ")})`)];
    return [];
  };
  const cases = all.map((verb) => {
    const words = verb.split(" ");
    const fixed = words.map((w, i) => sq(`${i + 1}: :(${w})`));
    const spec = [
      ...fixed,
      ...positional(verb, words.length + 1),
      "'--json[answer in JSON]'",
      ...flagsOf(verb).map(zTakes),
    ];
    return `    ${sq(verb)}) _arguments -s ${spec.join(" ")} ;;`;
  });
  const groupCases = GROUPS.map(
    (g) =>
      `    ${g}) if (( CURRENT == 3 )); then local -a sub; sub=(${describe(inGroup(g), short)}); _describe -t verbs ${sq(`kioku ${g} verb`)} sub; return; fi; verb="${g} $words[3]" ;;`,
  );
  const pluginCase = `    plugin) if (( CURRENT == 3 )); then compadd ${PLUGIN_HOSTS.join(" ")}; return; fi; if (( CURRENT == 4 )); then compadd ${PLUGIN_VERBS.join(" ")}; return; fi; _arguments ${PLUGIN_FLAGS.map(zTakes).join(" ")} '--json[answer in JSON]'; return ;;`;
  // A line with an apostrophe has it in zsh's own idiom, which closes and reopens the quotes around it.
  const zq = (s: string): string => `'${s.replace(/'/g, "'\"'\"'")}'`;
  const groupsTop = [...GROUPS, "plugin" as const].map((g) => zq(`${g}:${GROUP_DOES[g].replace(/:/g, " ")}`)).join(" ");
  // `kioku help <verb>`: the words of the first level, then a group's verbs, then, for `plugin`, a host's.
  const helpCase = `    help) if (( CURRENT == 3 )); then _describe -t verbs 'kioku verb' top; return; fi; if (( CURRENT == 4 )); then case $words[3] in ${GROUPS.map(
    (g) =>
      `${g}) local -a sub; sub=(${describe(inGroup(g), short)}); _describe -t verbs ${sq(`kioku ${g} verb`)} sub ;;`,
  ).join(
    " ",
  )} plugin) compadd ${PLUGIN_HOSTS.join(" ")} ;; esac; return; fi; if (( CURRENT == 5 )) && [[ $words[3] == plugin ]]; then compadd ${PLUGIN_VERBS.join(" ")}; fi; return ;;`;
  return [
    "#compdef kioku",
    `# Completion of kioku for zsh, generated by kioku ${VERSION} (kioku completion zsh).`,
    '_kioku_brains() { local -a b; b=(${(f)"$(' + BRAINS_SH + ')"}); compadd -a b }',
    '_kioku_keys() { local -a k; k=(${(f)"$(' + KEYS_SH + ')"}); compadd -a k }',
    `_kioku_targets() { _kioku_brains; compadd ${TIERS.join(" ")} }`,
    "_kioku() {",
    `  local -a top; top=(${describe(tops, (verb) => verb)} ${groupsTop})`,
    `  if (( CURRENT == 2 )); then top+=(${zq(`help:${HELP_DOES}`)}); _describe -t verbs 'kioku verb' top; return; fi`,
    "  local verb=$words[2]",
    "  case $verb in",
    ...groupCases,
    pluginCase,
    helpCase,
    "  esac",
    "  case $verb in",
    ...cases,
    "  esac",
    "}",
    // A profile that has not started the completion system has no `compdef`: start it, quietly, so the line works as it is.
    "(( $+functions[compdef] )) || { autoload -Uz compinit && compinit -i; }",
    "compdef _kioku kioku",
    "",
  ].join("\n");
}

function bash(): string {
  const words = (list: readonly string[]): string => list.join(" ");
  const flagCases = (verb: VerbName): string[] =>
    flagsOf(verb)
      .filter((f) => f.takes !== "none" && f.takes !== "free")
      .map((f) => {
        const t = f.takes;
        const reply =
          t === "brain"
            ? `$(${BRAINS_SH})`
            : t === "target"
              ? `$(${BRAINS_SH}) ${TIERS.join(" ")}`
              : t === "key"
                ? `$(${KEYS_SH})`
                : t === "file"
                  ? ""
                  : typeof t === "object"
                    ? t.choices.join(" ")
                    : "";
        return t === "file"
          ? `      --${f.name}) COMPREPLY=( $(compgen -f -- "$cur") ); return ;;`
          : `      --${f.name}) COMPREPLY=( $(compgen -W "${reply}" -- "$cur") ); return ;;`;
      });
  const cases = all.map((verb) => {
    const depth = verb.split(" ").length + 1;
    const lines: string[] = [`    ${verb.includes(" ") ? `"${verb}"` : verb})`];
    lines.push('      case "$prev" in', ...flagCases(verb), "      esac");
    const positional = positionalOf(verb);
    if (verb === "config") {
      lines.push(
        `      if (( COMP_CWORD == ${depth} )); then COMPREPLY=( $(compgen -W "${words(CONFIG_WORDS)}" -- "$cur") ); return; fi`,
      );
      lines.push(
        `      if (( COMP_CWORD == ${depth + 1} )); then COMPREPLY=( $(compgen -W "$(${KEYS_SH})" -- "$cur") ); return; fi`,
      );
    } else if (positional === "brain") {
      lines.push(
        `      if (( COMP_CWORD == ${depth} )) && [[ "$cur" != -* ]]; then COMPREPLY=( $(compgen -W "$(${BRAINS_SH})" -- "$cur") ); return; fi`,
      );
    } else if (positional !== undefined) {
      lines.push(
        `      if (( COMP_CWORD == ${depth} )) && [[ "$cur" != -* ]]; then COMPREPLY=( $(compgen -W "${words(positional.choices)}" -- "$cur") ); return; fi`,
      );
    }
    lines.push(
      `      COMPREPLY=( $(compgen -W "${words([...flagsOf(verb).map((f) => `--${f.name}`), "--json"])}" -- "$cur") ); return ;;`,
    );
    return lines.join("\n");
  });
  return [
    `# Completion of kioku for bash, generated by kioku ${VERSION} (kioku completion bash).`,
    "_kioku() {",
    '  local cur="${COMP_WORDS[COMP_CWORD]}" prev="${COMP_WORDS[COMP_CWORD-1]}"',
    '  local verb="${COMP_WORDS[1]}"',
    `  if (( COMP_CWORD == 1 )); then COMPREPLY=( $(compgen -W "${words([...tops, ...GROUPS, "plugin", "help"])}" -- "$cur") ); return; fi`,
    '  case "$verb" in',
    ...GROUPS.map(
      (g) =>
        `    ${g}) if (( COMP_CWORD == 2 )); then COMPREPLY=( $(compgen -W "${words(inGroup(g).map(short))}" -- "$cur") ); return; fi; verb="${g} \${COMP_WORDS[2]}" ;;`,
    ),
    // `kioku help <verb>`: the words of the first level, then a group's verbs, then, for `plugin`, a host's.
    `    help) if (( COMP_CWORD == 2 )); then COMPREPLY=( $(compgen -W "${words([...tops, ...GROUPS, "plugin"])}" -- "$cur") ); elif (( COMP_CWORD == 3 )); then case "\${COMP_WORDS[2]}" in ${GROUPS.map((g) => `${g}) COMPREPLY=( $(compgen -W "${words(inGroup(g).map(short))}" -- "$cur") ) ;;`).join(" ")} plugin) COMPREPLY=( $(compgen -W "${words(PLUGIN_HOSTS)}" -- "$cur") ) ;; esac; elif (( COMP_CWORD == 4 )) && [[ "\${COMP_WORDS[2]}" == plugin ]]; then COMPREPLY=( $(compgen -W "${words(PLUGIN_VERBS)}" -- "$cur") ); fi; return ;;`,
    `    plugin) if (( COMP_CWORD == 2 )); then COMPREPLY=( $(compgen -W "${words(PLUGIN_HOSTS)}" -- "$cur") ); elif (( COMP_CWORD == 3 )); then COMPREPLY=( $(compgen -W "${words(PLUGIN_VERBS)}" -- "$cur") ); else COMPREPLY=( $(compgen -W "${words([...PLUGIN_FLAGS.map((f) => `--${f.name}`), "--json"])}" -- "$cur") ); fi; return ;;`,
    "  esac",
    '  case "$verb" in',
    ...cases,
    "  esac",
    "}",
    "complete -F _kioku kioku",
    "",
  ].join("\n");
}

const SCRIPTS: Record<Shell, () => string> = { fish, zsh, bash };

/** `kioku completion fish|zsh|bash`: the script, to source. */
export const runCompletion: Handler = (args): Outcome => {
  const shell = args[0];
  if (args.length !== 1 || !(SHELLS as readonly string[]).includes(shell!))
    throw userError("completion takes one shell: fish, zsh or bash", "usage");
  const script = SCRIPTS[shell as Shell]();
  return { data: { shell, script }, text: script.trimEnd(), raw: true };
};
